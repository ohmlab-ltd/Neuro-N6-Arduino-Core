"""Generate the AED frontend tables and check them against ST's.

The parameters are those of Projects/Dpu/ai_model_config.h in ST's
STM32N6-GettingStarted-Audio project.

Usage:
    python tools/gen_aed_tables.py <path to user_mel_tables.c> [<output .c>]

The reference file is Projects/Dpu/user_mel_tables.c in ST's
STM32N6-GettingStarted-Audio project. N6_ST_AED may hold the path instead.
With an output path, tables that match are written there as C.
"""
import numpy as np, re, os, sys

FS, NFFT, NMEL, WINLEN = 16000.0, 512, 64, 400
FMIN, FMAX = 125.0, 7500.0

ST = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("N6_ST_AED", "")
if not ST:
    sys.exit(__doc__.split("Usage:")[1].strip())

# Periodic Hann window: divides by N, not N-1.
win = 0.5 - 0.5 * np.cos(2.0 * np.pi * np.arange(WINLEN) / WINLEN)

# HTK mel filterbank, sparse
def hz2mel(f):  return 2595.0 * np.log10(1.0 + f / 700.0)
def mel2hz(m):  return 700.0 * (10.0 ** (m / 2595.0) - 1.0)

mel_pts = np.linspace(hz2mel(FMIN), hz2mel(FMAX), NMEL + 2)
hz_pts  = mel2hz(mel_pts)
bin_hz  = FS / NFFT
nbins   = NFFT // 2 + 1
fft_hz  = np.arange(nbins) * bin_hz

lut, start_idx, stop_idx = [], [], []
for m in range(NMEL):
    lo, ctr, hi = hz_pts[m], hz_pts[m + 1], hz_pts[m + 2]
    w = np.zeros(nbins)
    for k in range(nbins):
        f = fft_hz[k]
        if lo < f < ctr:   w[k] = (f - lo) / (ctr - lo)
        elif ctr <= f < hi: w[k] = (hi - f) / (hi - ctr)
    nz = np.nonzero(w)[0]
    if len(nz) == 0:
        start_idx.append(0); stop_idx.append(0); continue
    a, b = int(nz[0]), int(nz[-1])
    start_idx.append(a); stop_idx.append(b)
    lut.extend(w[a:b + 1].tolist())

lut = np.array(lut)
start_idx = np.array(start_idx); stop_idx = np.array(stop_idx)
print(f"  generated: win[{len(win)}]  lut[{len(lut)}]  start[{len(start_idx)}]  stop[{len(stop_idx)}]")

# ST's tables
src = open(ST, encoding="utf-8", errors="ignore").read()

def grab(name, cast=float):
    m = re.search(re.escape(name) + r"\s*\[[0-9]*\]\s*=\s*\{(.*?)\}", src, re.S)
    if not m: return None
    body = m.group(1).replace("F", "").replace("f", "")
    return np.array([cast(x) for x in re.findall(r"[-+0-9.eE]+", body)])

st_win   = grab("user_win")
st_lut   = grab("user_melFiltersLut")
st_start = grab("user_melFiltersStartIndices", int)
st_stop  = grab("user_melFiltersStopIndices", int)
for name, arr in (("user_win", st_win), ("user_melFiltersLut", st_lut),
                  ("user_melFiltersStartIndices", st_start),
                  ("user_melFiltersStopIndices", st_stop)):
    if arr is None:
        sys.exit("no %s array in %s" % (name, ST))
print(f"  ST's     : win[{len(st_win)}]  lut[{len(st_lut)}]  "
      f"start[{len(st_start)}]  stop[{len(st_stop)}]")

print("\n  === comparison ===")
ok = True
def cmp(name, mine, theirs, tol):
    global ok
    if theirs is None or len(mine) != len(theirs):
        print(f"    {name:10s} LENGTH MISMATCH {len(mine)} vs "
              f"{0 if theirs is None else len(theirs)}"); ok = False; return
    err = np.max(np.abs(mine - theirs))
    good = err <= tol
    ok &= good
    print(f"    {name:10s} max abs error {err:.3e}   {'MATCH' if good else 'MISMATCH'}")

cmp("window", win, st_win, 1e-6)
cmp("start", start_idx, st_start, 0)
cmp("stop", stop_idx, st_stop, 0)
cmp("mel lut", lut, st_lut, 1e-5)

print()
if ok:
    print("  VERDICT: independently generated tables reproduce ST's exactly.")
    print("           The documented spec is fully understood; ship ours.")
else:
    print("  VERDICT: mismatch - do not ship these.")
    sys.exit(1)

# The C file
out = sys.argv[2] if len(sys.argv) > 2 else None
if out and os.path.abspath(out) == os.path.abspath(ST):
    sys.exit("the output path is the reference file: nothing written")
if out:
    def carr(name, arr, typ, fmt, per):
        s = f"const {typ} {name}[{len(arr)}] = {{\n"
        for i in range(0, len(arr), per):
            s += "  " + ", ".join(fmt % v for v in arr[i:i + per]) + ",\n"
        return s.rstrip(",\n") + "\n};\n\n"

    hdr = f'''/**
 * n6_aed_tables.c: AED frontend lookup tables.
 *
 * Generated by tools/gen_aed_tables.py; changes belong in the
 * generator instead. Parameters: log-mel, {NMEL} mel x 96 frames, NFFT {NFFT},
 * window {WINLEN}, hop 160, HTK, {FMIN:.0f}-{FMAX:.0f} Hz, {FS:.0f} Hz.
 */
#include "n6_aed_tables.h"

'''
    body  = carr("n6_aed_window", win, "float", "%.10eF", 4)
    body += carr("n6_aed_mel_lut", lut, "float", "%.10eF", 4)
    body += carr("n6_aed_mel_start", start_idx, "unsigned int", "%3u", 16)
    body += carr("n6_aed_mel_stop", stop_idx, "unsigned int", "%3u", 16)
    open(out, "w", encoding="utf-8", newline="\n").write(hdr + body)
    print(f"  wrote {out}")
