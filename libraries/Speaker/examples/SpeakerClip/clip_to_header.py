#!/usr/bin/env python3
"""Converts a slice of an audio file into song.h for SpeakerClip.ino.

Needs miniaudio or ffmpeg.

Usage: python clip_to_header.py clip.wav --kb 500 --start 0 --rate 22050

  --kb     maximum clip size in KB, default 500
  --dur    maximum clip length in seconds; the shorter limit applies
  --start  clip start in seconds, default 0
  --rate   sample rate in Hz, default 22050, snapped to one the SAI reaches
  --out    output path, default song.h beside the input
"""
import argparse, os, array

KER = 25_000_000  # SAI1 kernel clock in Hz, PLL4 400 MHz / 16

def achievable(req):
    d = max(1, min(63, round(KER / (req * 32))))
    return KER // (d * 32)

def decode_miniaudio(path, fs):
    import miniaudio
    d = miniaudio.decode_file(path, output_format=miniaudio.SampleFormat.SIGNED16,
                              nchannels=1, sample_rate=fs)
    return d.samples  # array('h')

def decode_ffmpeg(path, fs):
    import subprocess
    raw = subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error", "-i", path,
         "-f", "s16le", "-ac", "1", "-ar", str(fs), "-"],
        check=True, stdout=subprocess.PIPE).stdout
    a = array.array("h"); a.frombytes(raw); return a

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input")
    ap.add_argument("--kb", type=int, default=500)
    ap.add_argument("--dur", type=float, default=None)
    ap.add_argument("--start", type=float, default=0.0)
    ap.add_argument("--rate", type=int, default=22050)
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    out = a.out or os.path.join(os.path.dirname(os.path.abspath(a.input)), "song.h")

    fs = achievable(a.rate)
    print(f"requested {a.rate} Hz -> achievable {fs} Hz")

    try:
        samples = decode_miniaudio(a.input, fs)
        print(f"decoded {len(samples)} samples ({len(samples)/fs:.1f} s) via miniaudio")
    except ImportError:
        samples = decode_ffmpeg(a.input, fs)
        print(f"decoded {len(samples)} samples via ffmpeg")

    skip = int(a.start * fs)
    nmax = a.kb * 1024 // 2
    if a.dur is not None:
        nmax = min(nmax, int(a.dur * fs))
    clip = samples[skip: skip + nmax]
    n = len(clip)
    print(f"clip: {n} samples, {n*2/1024:.0f} KB, {n/fs:.1f} s (start {a.start:.1f}s)")

    with open(out, "w") as f:
        f.write("// auto-generated by clip_to_header.py\n#include <stdint.h>\n")
        f.write(f"const uint32_t kSongRate = {fs};\n")
        f.write(f"const uint32_t kSongLen  = {n};\n")
        f.write("const int16_t  kSong[] = {\n")
        for i in range(0, n, 20):
            f.write(",".join(str(v) for v in clip[i:i + 20]) + ",\n")
        f.write("};\n")
    print(f"wrote {out} ({os.path.getsize(out)/1024:.0f} KB)")

if __name__ == "__main__":
    main()
